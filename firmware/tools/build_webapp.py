"""Embed the device build of the web app (web/dist-device) into WebAppAssets.h.

Usage:
    cd web && npm run build:device
    python3 firmware/tools/build_webapp.py
"""

import gzip
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE_DIR = ROOT.parent / "web" / "dist-device"
OUTPUT = ROOT / "PingPongLauncher" / "src" / "net" / "WebAppAssets.h"
URL_PREFIX = "/app/"

MIME_TYPES = {
    ".html": "text/html; charset=utf-8",
    ".js": "application/javascript",
    ".css": "text/css",
    ".svg": "image/svg+xml",
    ".png": "image/png",
    ".ico": "image/x-icon",
    ".json": "application/json",
    ".woff2": "font/woff2",
}


def collect() -> list[Path]:
    """List every file of the build, index.html first."""
    files = sorted(path for path in SOURCE_DIR.rglob("*") if path.is_file())
    if not files:
        raise SystemExit(f"{SOURCE_DIR} is empty, run `npm run build:device` in web/ first")
    return sorted(files, key=lambda path: path.name != "index.html")


def url_for(path: Path) -> str:
    """Map a build file to the URL it is served at; index.html answers /app/."""
    relative = path.relative_to(SOURCE_DIR).as_posix()
    return URL_PREFIX if relative == "index.html" else URL_PREFIX + relative


def byte_array(symbol: str, data: bytes) -> str:
    """Render bytes as a PROGMEM C array, 20 values per line."""
    rows = []
    for start in range(0, len(data), 20):
        rows.append("  " + ", ".join(f"0x{value:02x}" for value in data[start:start + 20]) + ",")
    body = "\n".join(rows)
    return f"static const uint8_t {symbol}[] PROGMEM = {{\n{body}\n}};"


def render() -> tuple[str, int]:
    """Build the header text and return it with the total compressed size."""
    parts = [
        "#pragma once",
        "",
        "#include <Arduino.h>",
        "",
        "/**",
        " * Generated by firmware/tools/build_webapp.py from web/dist-device. Do not edit.",
        " * Files are gzip-compressed and served with Content-Encoding: gzip.",
        " */",
        "struct WebAppFile {",
        "  const char* path;",
        "  const char* mime;",
        "  const uint8_t* data;",
        "  size_t length;",
        "  bool immutable;",
        "};",
        "",
    ]
    entries = []
    total = 0
    for index, path in enumerate(collect()):
        data = gzip.compress(path.read_bytes(), compresslevel=9, mtime=0)
        total += len(data)
        symbol = f"WEBAPP_DATA_{index}"
        parts.append(byte_array(symbol, data))
        parts.append("")
        mime = MIME_TYPES.get(path.suffix, "application/octet-stream")
        immutable = "true" if path.parent.name == "assets" else "false"
        entries.append(f'  {{"{url_for(path)}", "{mime}", {symbol}, sizeof({symbol}), {immutable}}},')
    parts.append("static const WebAppFile WEBAPP_FILES[] = {")
    parts.extend(entries)
    parts.append("};")
    parts.append("")
    parts.append("static constexpr size_t WEBAPP_FILE_COUNT = sizeof(WEBAPP_FILES) / sizeof(WEBAPP_FILES[0]);")
    parts.append("")
    return "\n".join(parts), total


def main() -> None:
    """Write WebAppAssets.h and report the embedded size."""
    content, total = render()
    OUTPUT.write_text(content, encoding="utf-8")
    print(f"Wrote {OUTPUT.relative_to(ROOT.parent)} ({total} bytes gzip)")


if __name__ == "__main__":
    main()
