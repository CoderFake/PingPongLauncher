"""Embed firmware/portal/* into PortalAssets.h for the ESP32 captive portal.

Usage: python3 firmware/tools/build_portal.py
"""

from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE_DIR = ROOT / "portal"
OUTPUT = ROOT / "PingPongLauncher" / "src" / "net" / "PortalAssets.h"
DELIMITER = "PORTAL"

ASSETS = [
    ("PORTAL_HTML", "index.html"),
    ("PORTAL_CSS", "style.css"),
    ("PORTAL_JS", "app.js"),
]


def compact(text: str) -> str:
    """Strip indentation and blank lines to save flash without changing behavior."""
    lines = (line.strip() for line in text.splitlines())
    return "\n".join(line for line in lines if line)


def render() -> str:
    """Build the header text containing every asset as a PROGMEM raw string."""
    parts = [
        "#pragma once",
        "",
        "#include <Arduino.h>",
        "",
        "/**",
        " * Generated by firmware/tools/build_portal.py from firmware/portal/. Do not edit.",
        " */",
    ]
    for symbol, filename in ASSETS:
        body = compact((SOURCE_DIR / filename).read_text(encoding="utf-8"))
        if f"){DELIMITER}\"" in body:
            raise ValueError(f"{filename} contains the raw-string delimiter")
        parts.append(f'static const char {symbol}[] PROGMEM = R"{DELIMITER}({body}){DELIMITER}";')
        parts.append("")
    return "\n".join(parts)


def main() -> None:
    """Write PortalAssets.h and report its size."""
    content = render()
    OUTPUT.write_text(content, encoding="utf-8")
    print(f"Wrote {OUTPUT.relative_to(ROOT.parent)} ({len(content.encode())} bytes)")


if __name__ == "__main__":
    main()
